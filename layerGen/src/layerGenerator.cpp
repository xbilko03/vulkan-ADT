        generatedLayerFile << "}" << std::endl;
        generatedLayerFile << "}" << std::endl;
        generatedLayerFile << "}" << std::endl;
        generatedLayerFile << "layer_CheckPaused();" << std::endl;
        generatedLayerFile << "layer_HandlePendingBreak();" << std::endl;
        generatedLayerFile << "PFN_vkVoidFunction ret = " << VK_DEBUGGER_NAME << "_Find" << name << "(pName);" <<
                std::endl;
        generatedLayerFile << "if (ret == nullptr) {" << std::endl;
        generatedLayerFile << "layer_EnterDriver(false);" << std::endl;
        generatedLayerFile << "ret = " << next << ";" << std::endl;
        generatedLayerFile << "layer_LeaveDriver();" << std::endl;
        generatedLayerFile << "}" << std::endl;
        generatedLayerFile << "{" << std::endl;
