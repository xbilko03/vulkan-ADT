    void layerGenerator::printParameters(std::ofstream *output, auto *parameterList, bool typesIncluded) {
        uint32_t i = 0;
        /* for each parameter, print type and name */
        for (auto &param: *parameterList) {
            i++;
            if (typesIncluded) {
                *output << param.type << " " << param.name;
            } else {
                *output << param.name;
            }
            if (i < (*parameterList).size())
                *output << ", ";
        }
    }

    void layerGenerator::printParameter(std::ofstream *output, auto *parameterList, uint32_t index,
                                        bool typesIncluded) {
        uint32_t i = 0;
        /* for each parameter, print type and name */
        for (auto &param: *parameterList) {
            if (index == i) {
                if (typesIncluded) {
                    *output << param.type << " " << param.name;
                } else {
                    *output << param.name;
                }
                return;
            }
            i++;
        }
    }

