    void layerGenerator::generateFunctionIds() {
        std::vector<std::string> names;
        std::list<xmlParser::xCommand> *lists[] = {&xmlp.commandListInstances, &xmlp.commandListDevices};
        for (std::list<xmlParser::xCommand> *list: lists) {
            for (xmlParser::xCommand &item: *list) {
                if (std::find(ignoreCmdList.begin(), ignoreCmdList.end(), item.functName) != ignoreCmdList.end())
                    continue;
                if (functionIds.count(item.functName))
                    continue;
                functionIds[item.functName] = (uint16_t) (names.size() + 1);
                names.push_back(item.functName);
            }
        }
        for (std::string &name: ignoreLayerCmdList) {
            if (functionIds.count(name))
                continue;
            functionIds[name] = (uint16_t) (names.size() + 1);
            names.push_back(name);
        }

        functionIdsFile << "/*" << std::endl;
        functionIdsFile << "* Name		    : vkdbgFunctionsGenerated.hpp" << std::endl;
        functionIdsFile << "* Project	    : A Debugging Tool for Vulkan API (VkDebugger)" << std::endl;
        functionIdsFile <<
                "* Description  : Numbers of the Vulkan functions in the binary messages (transport/vkdbgFormat.hpp)" <<
                std::endl;
        functionIdsFile << "* [Careful! This file is generated by layerGen from vk.xml]" << std::endl;
        functionIdsFile << "*" << std::endl;
        functionIdsFile << "* Author        : Jozef Bilko (xbilko03), supervised by Ing. Jan Pe\xC4\x8Diva Ph.D." <<
                std::endl;
        functionIdsFile << "*/" << std::endl;
        functionIdsFile << "#pragma once" << std::endl << std::endl;
        functionIdsFile << "#include <cstdint>" << std::endl << std::endl;
        functionIdsFile << "namespace vkdebug {" << std::endl;
        functionIdsFile << "enum vulkanFunction : uint16_t {" << std::endl;
        functionIdsFile << "VKDBG_FN_NONE = 0," << std::endl;
        for (size_t i = 0; i < names.size(); i++)
            functionIdsFile << functionId(names[i]) << " = " << (i + 1) << "," << std::endl;
        functionIdsFile << "VKDBG_FN_COUNT = " << (names.size() + 1) << std::endl;
        functionIdsFile << "};" << std::endl << std::endl;
        functionIdsFile << "static const char* const functionNames[] = {" << std::endl;
        functionIdsFile << "\"\"," << std::endl;
        for (std::string &name: names)
            functionIdsFile << "\"" << name << "\"," << std::endl;
        functionIdsFile << "};" << std::endl;
        functionIdsFile << "}" << std::endl;
    }

