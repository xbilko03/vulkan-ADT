    void layerGenerator::createParameterStepsStruct(std::vector<parameterStep> &parameterStepsList, std::string type,
                                                    std::string name, std::string prefix, int attempts) {
        /* [xbilko03] to prevent the program getting stuck in a cycle, there are is only so many times a struct can be decompressed */
        attempts--;
        if (attempts < 0)
            return;
        auto *structs = &xmlp.structList;
        /* loaded struct type is always with the star character since it's the pointer that is passed in the function, it needs to be removed before it is possible to search by its type */
        std::string ptrlessType = type.substr(0, type.size() - 1);
        auto selectedStruct = (*structs)[ptrlessType];
        if (selectedStruct.structType == ptrlessType) {
            /* [xbilko03] null guard for pointers before trying to access the pointer's value with '->', flag it if pointer is null */
            addParameterStep(parameterStepsList, parameterStep::StepPointer, prefix + name, name, "");
            /* [xbilko03] prefix is to assure the structure's attribute is accessed e.g. structName->attributeName */
            prefix += name + "->";
            for (auto &item: selectedStruct.parameterList) {
                std::string outputType = item.type;
                /* [xbilko03] if there is enum, it is an array */
                if (item.enumType != "" || item.name == "color") {
                    outputType = "array";
                }
                /* [xbilko03] struct inside struct, send it for the decompression */
                if (isStruct(item.type)) {
                    /* [xbilko03] struct inside struct */
                    if (item.name == "ppGeometries" || item.name == "ppUsageCounts") {
                        item.name += "[array]";
                        item.type = "other";
                    }
                    createParameterStepsStruct(parameterStepsList, item.type, item.name, prefix, attempts);
                } else {
                    /* not a struct anymore, let it be collected */
                    createParameterStepsSingle(parameterStepsList, outputType, item.name, prefix);
                }
            }
            addParameterStep(parameterStepsList, parameterStep::StepEndPointer, "", "", "");
            return;
        }
    }

    void layerGenerator::createParameterStepsSingle(std::vector<parameterStep> &parameterStepsList, std::string type,
                                                    std::string name, std::string prefix) {
        std::string label = prefix + name;
        /* [xbilko03] imperfect xml parsing consequence exception */
        if (name == "blendConstants" || name == "pResults") {
            name += "[0]";
        }

        /* collect based on the parameter's type: */
        if (name == "sType") {
        } else if (type == "uint32_t*" || type == "void*" || type == "void" || name == "presentMask") {
        } else if (type == "uint32_t" || type == "int32_t" || type == "float" || type == "int" || type == "size_t" ||
                   type == "uint64_t" || type == "uint8_t" || type == "VkDeviceSize") {
            addParameterStep(parameterStepsList, parameterStep::StepValue, prefix + name, label, type);
        } else if (type == "VkBool32") {
            addParameterStep(parameterStepsList, parameterStep::StepValue, prefix + name, label, type);
        } else if (type == "char" || type == "char*") {
        } else if (type == "array") {
        } else if (isEnum(type)) {
        } else {
            /* [xbilko03] try a struct */
            if (isStruct(type)) {
                createParameterStepsStruct(parameterStepsList, type, name, prefix, 3);
            } else {
                /* [xbilko03] most likely a handle */
                addParameterStep(parameterStepsList, parameterStep::StepBits, prefix + name, label,
                                 type);
            }
        }
    }

    void layerGenerator::addParameterStep(std::vector<parameterStep> &parameterStepsList,
                                          parameterStep::parameterStepKind parameterStepType, std::string expression,
                                          std::string label, std::string type) {
        parameterStep op;
        op.parameterStepType = parameterStepType;
        op.expression = expression;
        op.label = label;
        op.type = type;
        parameterStepsList.push_back(op);
    }

    std::vector<layerGenerator::parameterStep> layerGenerator::createParameterSteps(
        std::list<xmlParser::xParameter> *parameterList) {
        std::vector<parameterStep> parameterStepsList;
        for (xmlParser::xParameter &parameter: *parameterList) {
            createParameterStepsSingle(parameterStepsList, parameter.type, parameter.name, "");
        }
        return parameterStepsList;
    }

    void layerGenerator::generateEncoderForLayer(std::ofstream *output,
                                                 const std::vector<parameterStep> &parameterStepsList) {
        for (const parameterStep &op: parameterStepsList) {
            switch (op.parameterStepType) {
                case parameterStep::StepValue:
                    *output << "writer.value(" << op.expression << ");" << std::endl;
                    break;
                case parameterStep::StepBits: *output << "writer.bits(" << op.expression << ");" << std::endl;
                    break;
                case parameterStep::StepPointer:
                    *output << "if (writer.pointer(" << op.expression << " != NULL)) {" << std::endl;
                    break;
                case parameterStep::StepEndPointer: *output << "}" << std::endl;
                    break;
            }
        }
    }

    void layerGenerator::generateDecoderForUi(std::ostream *output,
                                              const std::vector<parameterStep> &parameterStepsList) {
        for (const parameterStep &op: parameterStepsList) {
            switch (op.parameterStepType) {
                case parameterStep::StepValue:
                    *output << "r.value<" << op.type << ">(out, \"" << op.label << "\");" << std::endl;
                    break;
                case parameterStep::StepBits:
                    *output << "r.bits<" << op.type << ">(out, \"" << op.label << "\");" << std::endl;
                    break;
                case parameterStep::StepPointer:
                    *output << "if (r.pointer(out, \"" << op.label << "\")) {" << std::endl;
                    break;
                case parameterStep::StepEndPointer: *output << "}" << std::endl;
                    break;
            }
        }
    }

